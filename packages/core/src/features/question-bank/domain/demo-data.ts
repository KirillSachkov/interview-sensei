interface DemoQuestion {
  readonly topicKey: string;
  readonly text: string;
  readonly format: "open" | "quiz";
  readonly options: readonly { readonly id: string; readonly text: string }[];
  readonly correctOptionIds: readonly string[];
}
const open = (topicKey: string, text: string): DemoQuestion => ({
  topicKey,
  text,
  format: "open",
  options: [],
  correctOptionIds: [],
});
const quiz = (
  topicKey: string,
  text: string,
  [choices, correctOptionIds]: readonly [readonly string[], readonly string[]],
): DemoQuestion => ({
  topicKey,
  text,
  format: "quiz",
  options: choices.map((choice, index) => ({ id: String(index + 1), text: choice })),
  correctOptionIds,
});

